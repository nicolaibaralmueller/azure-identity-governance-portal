var LANG = 'en';

function t(key, vars) {
  var d = LANGS[LANG] || LANGS.en;
  var s = d[key] != null ? d[key] : LANGS.en[key] != null ? LANGS.en[key] : key;
  if (vars) s = s.replace(/\{(\w+)\}/g, function (m, n) { return vars[n] != null ? vars[n] : m; });
  return s;
}
function tn(key, n, vars) {
  var v = Object.assign({ n: n }, vars || {});
  return t(key + (Math.abs(n) === 1 ? '.one' : '.other'), v);
}
// A data value in the current language; values without a key are shown as they are.
function tv(prefix, value) {
  var k = prefix + '.' + value;
  return LANGS.en[k] != null ? t(k) : value;
}

function applyI18n(root) {
  function each(attr, fn) {
    var els = root.querySelectorAll('[' + attr + ']');
    for (var i = 0; i < els.length; i++) fn(els[i], t(els[i].getAttribute(attr)));
  }
  each('data-i18n', function (el, s) { el.textContent = s; });
  each('data-i18n-html', function (el, s) { el.innerHTML = s; });
  each('data-i18n-ph', function (el, s) { el.setAttribute('placeholder', s); });
  each('data-i18n-title', function (el, s) { el.setAttribute('title', s); });
  each('data-i18n-aria', function (el, s) { el.setAttribute('aria-label', s); });
}

// Unknown codes fall back to English. Also reveals the page (hidden while i18n-pending).
function setLanguage(code) {
  LANG = LANGS[code] ? code : 'en';
  document.documentElement.setAttribute('lang', LANG);
  applyI18n(document);
  if (typeof renderThemePicker === 'function') renderThemePicker();
  document.documentElement.classList.remove('i18n-pending');
}
